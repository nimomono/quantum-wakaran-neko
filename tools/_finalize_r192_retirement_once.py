from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def read(rel):
    return (ROOT / rel).read_text(encoding="utf-8")


def write(rel, text):
    (ROOT / rel).write_text(text, encoding="utf-8")


def replace_exact(text, old, new, label):
    count = text.count(old)
    if count != 1:
        raise SystemExit(f"{label}: expected exactly 1 match, found {count}")
    return text.replace(old, new, 1)


def replace_section(text, start_heading, end_heading, replacement, label):
    pattern = rf"(?ms)^{re.escape(start_heading)}\n.*?(?=^{re.escape(end_heading)}\n)"
    new_text, n = re.subn(pattern, lambda _m: replacement.rstrip() + "\n\n", text, count=1)
    if n != 1:
        raise SystemExit(f"{label}: expected exactly 1 section, found {n}")
    return new_text


